// Convert to GeoJSON format
export function getDistrictGeoJSON() {
    return {
        type: 'FeatureCollection' as const,
        features: odishaDistricts.map(district => ({
            type: 'Feature' as const,
            properties: {
                id: district.id,
                name_en: district.name_en,
                name_od: district.name_od,
                region: district.region,
                population: district.population,
                area_sq_km: district.area_sq_km,
                headquarters: district.headquarters,
                color: regionColors[district.region],
            },
            geometry: {
                type: 'Polygon' as const,
                coordinates: [
                    (districtPolygons[district.id] || []).map(([lat, lng]) => [lng, lat])
                ],
            },
        })),
    };
}
